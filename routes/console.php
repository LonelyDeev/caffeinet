<?php

use App\Console\Commands\CleanupSystem;
use App\Console\Commands\ExpireBroadcasts;
use App\Console\Commands\FlushPendingPushes;
use App\Console\Commands\NotifyUnacceptedOrders;
use Illuminate\Foundation\Inspiring;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Schedule;

Artisan::command('inspire', function () {
    $this->comment(Inspiring::quote());
})->purpose('Display an inspiring quote');

/*
|--------------------------------------------------------------------------
| زمان‌بندی‌های سیستم (فاز ۶)
|--------------------------------------------------------------------------
| موتور تخصیص سفارش: هر دقیقه سفارش‌های پخشیِ منقضی‌شده تعیین‌تکلیف می‌شوند
| (ری‌پخش خودکار یا انتقال به صف + پیامک). دقتِ ثانیه‌ای از طریق انقضای
| «تنبل» روی هر poll پنل‌ها تأمین می‌شود.
|
*/

Schedule::command(ExpireBroadcasts::class)->everyMinute()->withoutOverlapping();

/*
|--------------------------------------------------------------------------
| v25 — یادآوری درخواست‌های بی‌پذیرش
|--------------------------------------------------------------------------
| هر ۵ دقیقه: سفارش‌هایی که مدتی است پذیرفته نشده‌اند به مدیران اطلاع
| داده می‌شوند (اعلان + نوتیف دستگاه مدیر آفلاین + پیامک طبق تنظیمات).
| هر سفارش فقط یک‌بار (orders.unaccepted_notified_at).
|
*/

Schedule::command(NotifyUnacceptedOrders::class)->everyFiveMinutes()->withoutOverlapping()->onOneServer();

/*
|--------------------------------------------------------------------------
| v36 → v38 — تور ایمنی پوش اعلان‌های در انتظار
|--------------------------------------------------------------------------
| پوش دستگاه بر اساس «وضعیت کاربران» (تنظیمات ← اعلان‌ها و پوش، v38)
| ارسال می‌شود؛ پیش‌فرض «آفلاین» = همیشه در لحظهٔ ساخت اعلان (رفتار v37).
| ردیف‌های pending اعلان‌هایی هستند که لحظهٔ ساخت، سرویس پوش خاموش
| بوده یا (حالت «خودکار») گیرنده در آن لحظه آنلاین بوده — این فرمان
| دنبالشان می‌گردد و اگر گیرنده در پنجرهٔ ۱۵ دقیقه‌ای آفلاین شده باشد
| پوش را می‌فرستد.
|
*/

Schedule::command(FlushPendingPushes::class)
    ->everyMinute()
    ->runInBackground()          // سایر رخدادهای همان دقیقه را معطل نمی‌کند
    ->withoutOverlapping(5);     // قفل حداکثر ۵ دقیقه — حتی بعد از کرش خودش ریکاوری می‌شود

/*
|--------------------------------------------------------------------------
| v36 → v37 — ضربان کرون (نشانگر سلامت زمان‌بندی در تنظیمات عمومی)
|--------------------------------------------------------------------------
| هر اجرای schedule:run این مقدار را تازه می‌کند؛ اگر در تنظیمات «عمومی»
| رنگ قرمز دیدید یعنی کرون هاست (هر دقیقه) تنظیم نشده است و موتور
| پخش/پاکسازی کار نمی‌کنند.
|
| v37: دو مسیر مستقل — علاوه بر این تسک، رویداد ScheduledTaskStarting
| (در AppServiceProvider) هم CronHeartbeat::touch() را صدا می‌زند؛
| اینجا مسیر دوم است + ردپای فایل برای عیب‌یابی روی هاست.
|
*/

Schedule::call(fn () => \App\Support\CronHeartbeat::touch('cron-heartbeat'))
    ->everyMinute()
    ->name('cron-heartbeat');

/*
|--------------------------------------------------------------------------
| پاکسازی دوره‌ای (فاز ۱۱ — امنیت و لانچ)
|--------------------------------------------------------------------------
| هر شب ساعت ۰۳:۳۰: کد OTP منقضی، اعلان/لاگ‌های قدیمی طبق نگهداشت
| تنظیم‌شدهٔ پنل + روتیشن حجمی لاگ لاراول. گزارش آخرین اجرا در
| settings (system.cleanup.last) — نمایش زنده در /admin/system.
|
*/

Schedule::command(CleanupSystem::class)->dailyAt('03:30')->withoutOverlapping()->onOneServer();
